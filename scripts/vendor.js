import { build } from "esbuild";
import fs from "node:fs/promises";
await fs.rm("assets/client.js.LEGAL.txt", { force: true });
await build({
  entryPoints: ["src/client.js"],
  bundle: true,
  minify: true,
  format: "iife",
  outfile: "assets/client.js",
  legalComments: "linked",
});
await build({
  stdin: {
    contents: "import mermaid from 'mermaid';window.mermaid=mermaid;",
    resolveDir: process.cwd(),
  },
  bundle: true,
  minify: true,
  format: "iife",
  outfile: "assets/mermaid.js",
  legalComments: "linked",
});
await fs.copyFile(
  "node_modules/katex/dist/katex.min.css",
  "assets/katex.min.css",
);
await fs.cp("node_modules/katex/dist/fonts", "assets/fonts", {
  recursive: true,
});
const lock = JSON.parse(await fs.readFile("package-lock.json", "utf8"));
let notices =
  "# Third-party notices\n\nGenerated by `npm run vendor`. Runtime assets are local; installation requires network access.\n\n";
for (const [key, pkg] of Object.entries(lock.packages)) {
  if (!key || pkg.dev) continue;
  notices += `## ${key.replace("node_modules/", "")} ${pkg.version}\n\nLicense: ${pkg.license || "See package license"}\n\n`;
  for (const name of [
    "LICENSE",
    "LICENSE.md",
    "LICENSE.txt",
    "license",
    "license.md",
  ]) {
    try {
      notices +=
        "```text\n" +
        (await fs.readFile(`${key}/${name}`, "utf8")) +
        "\n```\n\n";
      break;
    } catch {
      /* Case varies by package. */
    }
  }
}
const pixelPackage = JSON.parse(
  await fs.readFile("node_modules/@zenbu-labs/pixel/package.json", "utf8"),
);
notices += `## Patched Electron runtime ${pixelPackage.config.electron}\n\nDownloaded by Pixel during installation, not included in this repository. Electron is MIT licensed; Chromium and its components have additional licenses. Full notices are distributed in node_modules/@zenbu-labs/pixel/electron/dist/LICENSE and LICENSES.chromium.html.\n`;
await fs.writeFile("THIRD_PARTY_NOTICES.md", notices.replace(/\r\n/g,"\n"));
